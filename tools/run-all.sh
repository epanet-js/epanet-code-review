#!/bin/sh
# Run every issue's test and record the results in verification.md.
#
#   tools/run-all.sh             all issues (JOBS=4 run in parallel)
#   tools/run-all.sh SIM-01 ...  only these issues (verification.md is not written)
#
# For each issue:
#   Unpatched    the test against EPANET 83e25bb; it should show the bug
#   Patched      against EPANET with the issue's own patch; it should PASS
#   All patches  against EPANET with every patch applied together
#   Unit tests   EPANET's own Boost tests, built with the issue's patch
set -eu

HERE=$(cd "$(dirname "$0")/.." && pwd)
RESULTS=$HERE/.build/results

# Issues whose patch changes only documentation: the test shows the
# behaviour, and passes before and after the patch
DOCS_ONLY=" SIM-04 API-04 FILE-19 "

verdict() {
    # The last line of run-test.sh is "<ID> [<label>]: <VERDICT> (exit code n)"
    tail -1 | awk '/\]: / {print $3; found = 1} END {if (!found) print "ERROR"}'
}

# Row mode: one issue, used by the parallel runner below
if [ "${1:-}" = "--row" ]; then
    ID=$2
    LOG=$RESULTS/$ID.log
    BASE=$(sh "$HERE/tools/run-test.sh" "$ID" 2>&1 | tee "$LOG" | verdict)
    PATCHED=$(sh "$HERE/tools/run-test.sh" "$ID" --patched 2>&1 | tee -a "$LOG" | verdict)
    if [ -f "$HERE/.build/all/stamp" ]; then
        ALL=$(sh "$HERE/tools/run-test.sh" "$ID" --all 2>&1 | tee -a "$LOG" | verdict)
    else
        ALL="n/a"
    fi
    if "$HERE/tools/build-epanet.sh" "$ID" --unit-tests >> "$LOG" 2>&1; then
        UNIT=pass
    else
        UNIT=FAIL
    fi
    echo "$ID|$BASE|$PATCHED|$ALL|$UNIT" > "$RESULTS/$ID.txt"
    echo "$ID: unpatched $BASE, patched $PATCHED, all patches $ALL, unit tests $UNIT"
    exit 0
fi

mkdir -p "$RESULTS"
rm -f "$RESULTS"/*.txt

if [ $# -gt 0 ]; then
    IDS=$*
else
    IDS=$(ls -d "$HERE"/*/*/ | sed -n 's|.*/\([A-Z]*-[0-9]*\)-[^/]*/$|\1|p')
fi

# Build the shared libraries first, so the parallel jobs do not race for them
"$HERE/tools/build-epanet.sh" base
if ! "$HERE/tools/build-epanet.sh" all; then
    echo "The patches do not apply together; skipping the all-patches column" >&2
    rm -f "$HERE/.build/all/stamp"
fi

echo $IDS | tr ' ' '\n' | xargs -P "${JOBS:-4}" -I{} sh "$HERE/tools/run-all.sh" --row {}

[ $# -gt 0 ] && exit 0

# Write verification.md
OUT=$HERE/verification.md
{
    echo "# Verification"
    echo
    echo "Generated by \`tools/run-all.sh\` on $(date '+%Y-%m-%d') ($(uname -sm), $(cc --version | head -1))."
    echo
    echo "Each test was compiled and run against EPANET 83e25bb built with AddressSanitizer and UndefinedBehaviorSanitizer:"
    echo
    echo "- **Unpatched**: the test should show the bug (\`FAIL\`, \`CRASH\` or \`HANG\`)."
    echo "- **Patched**: with the issue's own patch, the test should \`PASS\`."
    echo "- **All patches**: with every patch in this review applied together, the test should \`PASS\`."
    echo "- **Unit tests**: EPANET's own 6 Boost test suites, built with the issue's patch."
    echo
    echo "Issues whose patch only corrects documentation are marked \"docs fix\". Their test shows the behaviour and passes both before and after the patch."
    echo
    echo "| ID | Unpatched | Patched | All patches | Unit tests | |"
    echo "|---|---|---|---|---|---|"
    for ID in $IDS; do
        IFS='|' read -r id base patched all unit < "$RESULTS/$ID.txt"
        case "$DOCS_ONLY" in
            *" $ID "*) expected_base=PASS ;;
            *)         expected_base=bug ;;
        esac
        if [ "$expected_base" = PASS ]; then
            ok=$([ "$base" = PASS ] && [ "$patched" = PASS ] && echo "docs fix" || echo "**check**")
        else
            ok=$([ "$base" != PASS ] && [ "$base" != ERROR ] && [ "$patched" = PASS ] && echo "✓" || echo "**check**")
        fi
        [ "$all" != PASS ] && [ "$all" != "n/a" ] && ok="**check**"
        [ "$unit" != pass ] && ok="**check**"
        echo "| $ID | $base | $patched | $all | $unit | $ok |"
    done
} > "$OUT"
echo "Wrote $OUT"
